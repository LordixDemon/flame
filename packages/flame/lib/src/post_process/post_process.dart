/// A way to apply effects to a whole component tree.
///
/// This is specially useful for applying effects based on [FragmentShader]s.
///
/// Post processes are created by sub-classing  and implementing the
/// [postProcess] method.
///
/// Within the [postProcess] method, you can use the [renderSubtree] method
/// to render the component tree. This method will take care of setting up
/// the context for the post process, so children can know if they are being
/// rendered within a post process by using
/// `PostProcessingContextFinder.findPostProcessFromContext`.
///
/// The subtree of a post process is the children of the owner, if it is a
/// `PostProcessComponent`, or the [World] if
/// the owner is a [CameraComponent]. When using a
/// [PostProcessSequentialGroup], the subtree also includes the preceding
/// post processes in the group.
///
/// Another useful method is [rasterizeSubtree], which will render the component
/// tree to an image. This is useful for using such image as a texture in
/// a shader.
///
/// Post process can be combined using [PostProcessGroup] or
/// [PostProcessSequentialGroup] to build a chain of post processes.
///
/// Post processes can be used via [CameraComponent.postProcess] or
/// `PostProcessComponent`.
///
/// A post process may even render a subtree multiple times if it needs to.
/// In addition, if children check for
/// `PostProcessingContextFinder.findPostProcessFromContext`,
/// they may even render differently in each render pass.
/// Ideal for mask textures.
///
/// See also:
/// - `PostProcessComponent` for a component that applies a post process
/// - [PostProcessGroup] for a group of post processes that will be applied
///   in parallel
/// - [PostProcessSequentialGroup] for a group of post processes that will be
///   applied in sequence
/// - [FragmentProgram] for a way to create post processes using fragment
///   shaders
/// - `PostProcessingContextFinder` for a way to access the post process
///   context from within a component during rendering
abstract class PostProcess({double? pixelRatio}) {
  /// Whether [pixelRatio] was omitted at construction time and should track
  /// live display `devicePixelRatio` and camera `worldRenderScale` changes.
  final bool autoSyncDevicePixelRatio = pixelRatio == null;

  /// The pixel ratio of the screen. The image generated by [rasterizeSubtree]
  /// is rendered at this many pixels per logical pixel, so that it stays sharp
  /// on high density screens.
  ///
  /// Defaults to [FlutterView.devicePixelRatio] when available, or `1.0`.
  double pixelRatio =
      pixelRatio ??
      (PlatformDispatcher.instance.views.isNotEmpty
          ? PlatformDispatcher.instance.views.first.devicePixelRatio
          : 1.0);

  /// Updates [pixelRatio] to [targetRatio] when [autoSyncDevicePixelRatio] is
  /// `true`.
  @internal
  @mustCallSuper
  void syncDevicePixelRatio(double targetRatio) {
    if (autoSyncDevicePixelRatio) {
      pixelRatio = targetRatio;
    }
  }

  /// Similarly to components, post processes can be loaded asynchronously.
  ///
  /// Use this to load any resources needed for the post process. This is called
  /// when the post process is added to a [CameraComponent] or a
  /// `PostProcessComponent`.
  ///
  /// See also:
  /// - [Component.onLoad] for more information on how to load components.
  FutureOr<void> onLoad() {}

  /// This method is called every frame to update the post process.
  ///
  /// Use this to update any state that needs to be updated every frame.
  /// This is called after the [update] method of the [Component] class.
  ///
  /// An example of usage is to update the time uniform of a shader.
  void update(double dt) {}

  /// Called when the owning `PostProcessComponent` is removed from the tree.
  ///
  /// Override to release transient per-mount resources (such as held frame
  /// textures) while keeping the post process reusable if mounted again.
  void onRemove() {}

  /// Permanently releases native GPU resources (such as [FragmentShader]s or
  /// [ui.Image]s) owned by this post process.
  @mustCallSuper
  void dispose() {
    onRemove();
  }

  void Function(Canvas)? _renderTree;
  void Function(PostProcess?)? _updateContext;
  Vector2? _size;
  Object? _currentPassTag;

  /// Monotonic counter incremented on every [rasterizeSubtree] or
  /// [rasterizePass] `Picture.toImageSync` GPU texture allocation.
  @internal
  static int debugRasterizeCount = 0;

  /// Whether this post-process currently acts as an identity pass-through
  /// (for example `enabled == false` or `intensity == 0`) and can be bypassed
  /// without allocating offscreen layers or textures.
  bool get isEffectivelyNoOp => false;

  /// Whether this post-process can consume an already-rasterized [ui.Image]
  /// directly via [renderFromImage] without invoking [rasterizeSubtree].
  bool get supportsImageInput => false;

  /// Renders this post-process directly from [inputImage] onto [canvas] within
  /// logical [size], returning `true` if handled or `false` if unsupported.
  bool renderFromImage(ui.Image inputImage, Vector2 size, Canvas canvas) =>
      false;

  /// Invokes the underlying subtree render callback without overriding the
  /// active post-process context.
  @protected
  void renderRawSubtree(Canvas canvas) => _renderTree!(canvas);

  /// Forwards a post-process context update to the owning camera or component.
  @protected
  void updateSubtreeContext(PostProcess? postProcess) =>
      _updateContext?.call(postProcess);

  /// Tag identifying the currently executing [rasterizePass] invocation, or
  /// `null` during standard [rasterizeSubtree] / [renderSubtree] passes.
  ///
  /// Descendant components can inspect this via
  /// `findPostProcessFromContext()?.currentPassTag` to alter their rendering
  /// per pass (for example, drawing emissive masks or depth weights).
  Object? get currentPassTag => _currentPassTag;

  /// This method is called to render the post process, to be called by the
  /// "owner" of
  /// the post process, like a [CameraComponent] or a `PostProcessComponent`.
  @internal
  void render(
    Canvas canvas,
    Vector2 size,
    ValueSetter<Canvas> renderTree,
    ValueSetter<PostProcess?> updateContext,
  ) {
    _renderTree = renderTree;
    _updateContext = updateContext;
    _size = size;

    canvas.save();
    postProcess(size, canvas);
    canvas.restore();

    _size = null;
    _renderTree = null;
    _updateContext = null;
  }

  /// One of the two methods that subclasses should invoke to render the
  /// what is considered the "subtree" of the post process.
  ///
  /// Differently from [renderSubtree], this method will rasterize the
  /// subtree to an image, which can be used as a texture in a shader. This
  /// is an expensive operation, so it should be used sparingly.
  ///
  /// The image is `pixelRatio` times the size of the post process and the
  /// subtree fills all of it, so a shader can sample it with texture
  /// coordinates going from 0 to 1 across the size of the post process.
  ///
  /// This method will set the context of the post process, so that
  /// components can know they are being rendered within a post process.
  @nonVirtual
  @protected
  ui.Image rasterizeSubtree() {
    final recorder = PictureRecorder();
    final innerCanvas = TelemetryCanvas.wrapOffscreenIfActive(Canvas(recorder))
      ..scale(pixelRatio);

    renderSubtree(innerCanvas);

    final picture = recorder.endRecording();
    try {
      debugRasterizeCount++;
      return picture.toImageSync(
        math.max(1, (pixelRatio * _size!.x).ceil()),
        math.max(1, (pixelRatio * _size!.y).ceil()),
      );
    } finally {
      picture.dispose();
    }
  }

  /// Rasterizes the subtree into an offscreen [ui.Image] scaled by
  /// `pixelRatio * resolutionScale` (clamped so dimensions stay `>= 1x1`),
  /// optionally tagging [currentPassTag] with [passTag] and pushing
  /// [cameraRenderPass] onto `CameraComponent.currentRenderPass` for the
  /// duration of the pass.
  @nonVirtual
  @protected
  ui.Image rasterizePass({
    double resolutionScale = 1.0,
    Object? passTag,
    RenderPass? cameraRenderPass,
  }) {
    final baseDpr = pixelRatio.clamp(0.5, 3.0);
    final effectiveScale = (baseDpr * resolutionScale.clamp(0.125, 2.0)).clamp(
      0.0625,
      4.0,
    );
    final imgW = math.max(1, (_size!.x * effectiveScale).ceil());
    final imgH = math.max(1, (_size!.y * effectiveScale).ceil());

    final previousTag = _currentPassTag;
    _currentPassTag = passTag;
    if (cameraRenderPass != null) {
      CameraComponent.pushRenderPass(cameraRenderPass);
    }
    try {
      final recorder = PictureRecorder();
      final innerCanvas = TelemetryCanvas.wrapOffscreenIfActive(
        Canvas(recorder),
      );
      if (effectiveScale != 1.0) {
        innerCanvas.scale(effectiveScale, effectiveScale);
      }
      renderSubtree(innerCanvas);
      final picture = recorder.endRecording();
      try {
        debugRasterizeCount++;
        return picture.toImageSync(imgW, imgH);
      } finally {
        picture.dispose();
      }
    } finally {
      if (cameraRenderPass != null) {
        CameraComponent.popRenderPass();
      }
      _currentPassTag = previousTag;
    }
  }

  /// One of the two methods that subclasses should invoke to render the
  /// what is considered the "subtree" of the post process.
  ///
  /// This method will set the context of the post process, so that
  /// components can know they are being rendered within a post process.
  /// See `PostProcessingContextFinder.findPostProcessFromContext`.
  @nonVirtual
  @protected
  void renderSubtree(Canvas canvas) {
    canvas.save();
    _updateContext!(this);
    _renderTree!(canvas);
    _updateContext!(null);
    canvas.restore();
  }

  /// There the effects of the post process are applied. This is where you
  /// should implement the logic of the post process. Including eventual calls
  /// to [rasterizeSubtree] and [renderSubtree].
  ///
  /// If neither is called the post process will not render anything apart from
  /// what is implemented in this method.
  void postProcess(Vector2 size, Canvas canvas) {
    renderSubtree(canvas);
  }
}

/// A [PostProcess] that applies [postProcesses] in parallel.
///
/// Every post process receives the same subtree: the subtree of the group,
/// such as the world when used as [CameraComponent.postProcess]. They are
/// rendered in order onto the same canvas, so later post processes are drawn
/// over earlier ones.
///
/// Each post process that calls [renderSubtree] or [rasterizeSubtree]
/// renders the subtree again, so the subtree is rendered at least once for
/// every such post process in the group.
///
/// See also:
/// - [PostProcess] for more information on what the "subtree" of a post
///   process is.
/// - [PostProcessSequentialGroup] to apply post processes on top of each
///   other instead, each of them receiving the previous one as its subtree.
class PostProcessGroup({
  required final List<PostProcess> postProcesses,
}) extends PostProcess {
  @override
  void syncDevicePixelRatio(double targetRatio) {
    super.syncDevicePixelRatio(targetRatio);
    for (final postProcess in postProcesses) {
      postProcess.syncDevicePixelRatio(targetRatio);
    }
  }

  @override
  Future<void> onLoad() async {
    for (final postProcess in postProcesses) {
      await postProcess.onLoad();
    }
  }

  @override
  void update(double dt) {
    for (final postProcess in postProcesses) {
      postProcess.update(dt);
    }
  }

  @override
  void onRemove() {
    for (final postProcess in postProcesses) {
      postProcess.onRemove();
    }
  }

  @override
  void dispose() {
    for (final postProcess in postProcesses) {
      postProcess.dispose();
    }
    super.dispose();
  }

  @override
  void render(
    Canvas canvas,
    Vector2 size,
    ValueSetter<Canvas> renderTree,
    ValueSetter<PostProcess?> updateContext,
  ) {
    for (final postProcess in postProcesses) {
      postProcess.render(canvas, size, renderTree, updateContext);
    }
  }
}

/// A [PostProcess] that applies [postProcesses] one after another, in order.
///
/// The first post process receives the subtree of the group, such as the
/// world when used as [CameraComponent.postProcess]. Each following post
/// process receives the previous one as its subtree, so the last post
/// process is applied last, on top of all the others.
///
/// For example, with `[Grayscale(), DropShadow()]`, the subtree of
/// `DropShadow` is the grayscale version of the group's subtree.
///
/// Every call to [renderSubtree] or [rasterizeSubtree] runs the preceding
/// post processes again, so a post process that renders its subtree more
/// than once, like a drop shadow, gets the same result each time.
///
/// See also:
/// - [PostProcess] for more information on what the "subtree" of a post
///   process is.
/// - [PostProcessGroup] to apply post processes in parallel, each of them
///   receiving the same subtree.
class PostProcessSequentialGroup({
  required super.postProcesses,
}) extends PostProcessGroup {
  final List<PostProcess> _contextStack = <PostProcess>[];

  @override
  void render(
    Canvas canvas,
    Vector2 size,
    ValueSetter<Canvas> renderTree,
    ValueSetter<PostProcess?> updateContext,
  ) {
    _contextStack.clear();
    void handleContext(PostProcess? next) {
      if (next != null) {
        _contextStack.add(next);
        updateContext(next);
      } else {
        if (_contextStack.isNotEmpty) {
          _contextStack.removeLast();
        }
        updateContext(_contextStack.isEmpty ? null : _contextStack.last);
      }
    }

    canvas.save();
    try {
      _renderFrom(
        postProcesses.length - 1,
        canvas,
        size,
        renderTree,
        handleContext,
      );
    } finally {
      _contextStack.clear();
      updateContext(null);
      canvas.restore();
    }
  }

  /// Renders the post process at [index], whose subtree is the post process
  /// before it, down to the original [renderTree].
  ///
  /// Each level gets its own subtree callback, so a post process can render
  /// its subtree more than once and the preceding post processes run every
  /// time.
  void _renderFrom(
    int index,
    Canvas canvas,
    Vector2 size,
    ValueSetter<Canvas> renderTree,
    ValueSetter<PostProcess?> updateContext,
  ) {
    if (index < 0) {
      renderTree(canvas);
      return;
    }
    postProcesses[index].render(
      canvas,
      size,
      (canvas) =>
          _renderFrom(index - 1, canvas, size, renderTree, updateContext),
      updateContext,
    );
  }
}
